"""Build the active Noto Sans TC WOFF2 font; --rounded rebuilds archived assets.

Sources are pinned official GenSen Rounded 2.100 TW OTFs. Keep their receipts
in data/cache/font-build/gensen; this build is offline and verifies each hash.
"""
import hashlib
import json
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path('data/cache/font-build/tools').resolve()))
from fontTools import subset
from fontTools.ttLib import TTFont

if '--rounded' not in sys.argv:
    root = Path('data/cache/font-build')
    source = root / 'NotoSansTC-variable.ttf'
    receipt = json.loads(source.with_suffix('.ttf.receipt.json').read_text(encoding='utf-8-sig'))
    assert hashlib.sha256(source.read_bytes()).hexdigest() == receipt['sha256']
    text = ''.join(p.read_text(encoding='utf-8') for p in Path('src').rglob('*')
                   if p.suffix in ('.ts', '.tsx', '.json', '.css'))
    characters = set(text) | {chr(i) for i in range(32, 127)}
    characters |= set('，。！？：；（）「」『』【】％／－＋～↗→•·…')
    font = TTFont(source)
    points = {ord(c) for c in characters} & set(font.getBestCmap())
    options = subset.Options()
    options.name_IDs = ['*']
    options.name_legacy = True
    options.notdef_glyph = True
    options.recommended_glyphs = True
    builder = subset.Subsetter(options=options)
    builder.populate(unicodes=points)
    builder.subset(font)
    font.flavor = 'woff2'
    target = Path('public/fonts/FlightQuerySans.woff2')
    font.save(target)
    result = {'family': 'Noto Sans TC', 'sourceUrl': receipt['url'],
              'sourceSha256': receipt['sha256'], 'license': 'OFL.txt',
              'format': 'woff2', 'weightRange': '100 900', 'glyphs': len(points),
              'bytes': target.stat().st_size,
              'sha256': hashlib.sha256(target.read_bytes()).hexdigest(),
              'coverage': 'ASCII plus display characters from src; system sans fallback for other input characters'}
    Path('public/fonts/NOTICE.json').write_text(json.dumps(result, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(result))
    sys.exit(0)

SOURCE = Path('data/cache/font-build/gensen')
OUTPUT = Path('public/fonts/rounded')
OUTPUT.mkdir(parents=True, exist_ok=True)
WEIGHTS = {400: 'R', 500: 'M', 700: 'B'}


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def strings(value):
    if isinstance(value, str):
        return value
    if isinstance(value, list):
        return ''.join(strings(item) for item in value)
    if isinstance(value, dict):
        return ''.join(strings(item) for item in value.values())
    return ''


text = ''
for path in Path('src').rglob('*'):
    if path.suffix not in ('.ts', '.tsx', '.json', '.css') or path.name == 'rounded-font-fallback.css':
        continue
    content = path.read_text(encoding='utf-8')
    text += content
    if path.suffix == '.json':
        text += strings(json.loads(content))
    text += ''.join(chr(int(code, 16)) for code in re.findall(r'\\u([0-9a-fA-F]{4})', content))
characters = set(text) | set(chr(i) for i in range(32, 127))
characters |= set('，。！？：；（）「」『』【】％／－＋～↗→•·…')
requested = {ord(c) for c in characters}


def ranges(points):
    groups = []
    for point in sorted(points):
        if groups and point == groups[-1][1] + 1:
            groups[-1][1] = point
        else:
            groups.append([point, point])
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in groups)


def save_subset(source, points, target, weight):
    font = TTFont(source)
    options = subset.Options()
    options.flavor = 'woff2'
    options.name_IDs = ['*']
    options.name_legacy = True
    options.notdef_glyph = True
    options.recommended_glyphs = True
    builder = subset.Subsetter(options=options)
    builder.populate(unicodes=points)
    builder.subset(font)
    style = {400: 'Regular', 500: 'Medium', 700: 'Bold'}[weight]
    names = {1: 'Flight Query Rounded', 2: style,
             3: f'FlightQueryRounded-{style}-2.100',
             4: f'Flight Query Rounded {style}',
             6: f'FlightQueryRounded-{style}',
             16: 'Flight Query Rounded', 17: style}
    for record in font['name'].names:
        if record.nameID in names:
            record.string = names[record.nameID].encode(record.getEncoding())
    font.flavor = 'woff2'
    font.save(target)
    font.close()
    return {'file': f'rounded/{target.name}', 'weight': weight,
            'glyphs': len(points), 'bytes': target.stat().st_size,
            'sha256': digest(target)}


assets = []
sources = []
rules = ['/* Generated by scripts/build-query-font.py; non-core glyphs load on demand. */']
for weight, suffix in WEIGHTS.items():
    source = SOURCE / f'GenSenRounded2TW-{suffix}.otf'
    receipt = json.loads(source.with_suffix('.otf.receipt.json').read_text(encoding='utf-8-sig'))
    assert digest(source) == receipt['sha256'], f'Font source hash mismatch: {source}'
    sources.append({**receipt, 'weight': weight})
    font = TTFont(source)
    supported = set(font.getBestCmap())
    font.close()
    core = requested & supported
    assets.append(save_subset(source, core, OUTPUT / f'{weight}-core.woff2', weight))
    # Uncommon input/API characters retain the same family without loading all CJK.
    blocks = {}
    for point in supported - core:
        blocks.setdefault(point // 2048, set()).add(point)
    for block, points in sorted(blocks.items()):
        target = OUTPUT / f'{weight}-u{block * 2048:04x}.woff2'
        assets.append(save_subset(source, points, target, weight))
        rules.append(
            "@font-face {\n  font-family: 'Flight Query Rounded Extended';\n"
            f"  src: url('/fonts/rounded/{target.name}') format('woff2');\n"
            f"  font-style: normal;\n  font-weight: {weight};\n"
            f"  font-display: swap;\n  unicode-range: {ranges(points)};\n}}"
        )
    print(f'Built {weight}: {len(core)} core glyphs, {len(blocks)} on-demand blocks', flush=True)

Path('src/app/rounded-font-fallback.css').write_text('\n\n'.join(rules) + '\n', encoding='utf-8')
Path('public/fonts/GenSenRounded-OFL.txt').write_bytes((SOURCE / 'OFL.txt').read_bytes())
notice = {
    'family': 'Flight Query Rounded', 'derivedFrom': 'GenSen Rounded 2.100 TW',
    'upstream': 'https://github.com/ButTaiwan/gensen-font',
    'license': 'GenSenRounded-OFL.txt', 'format': 'woff2',
    'weights': list(WEIGHTS), 'sources': sources, 'assets': assets,
    'coverage': 'Core: current interface/data text. On-demand blocks: complete upstream character set.',
    'supportedCharacters': len(supported),
    'coreBytes': sum(a['bytes'] for a in assets if a['file'].endswith('-core.woff2')),
}
Path('public/fonts/rounded/NOTICE.json').write_text(json.dumps(notice, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
print(json.dumps({key: notice[key] for key in ('derivedFrom', 'weights', 'supportedCharacters', 'coreBytes')}))
